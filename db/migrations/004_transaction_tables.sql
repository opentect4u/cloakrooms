-- 004 · Synced transactions (luggage check-in/out, bills) and refused sync rows (CLAUDE.md §5).

CREATE TABLE IF NOT EXISTS td_luggage_in_out (
  trans_id      VARCHAR(36)  NOT NULL COMMENT 'UUID created on the check-in device (QR)',
  customer_id   INT UNSIGNED NOT NULL,
  receipt_no    VARCHAR(20)  NOT NULL COMMENT '<user_code>-<5 digits>',
  receipt_dt    DATE         NOT NULL COMMENT 'check-in date, local (IST)',
  user_id_in    INT UNSIGNED NOT NULL COMMENT 'md_user.id',
  device_id_in  VARCHAR(100) NOT NULL,
  shift_id_in   INT UNSIGNED NULL,
  date_time_in  DATETIME     NOT NULL,
  pasn_name     VARCHAR(200) NOT NULL,
  pasn_mob_no   VARCHAR(15)  NOT NULL,
  pnr_no        VARCHAR(20)  NOT NULL,
  luggage_qty   SMALLINT UNSIGNED NOT NULL,
  id_proof_id   INT UNSIGNED NOT NULL,
  id_number     VARCHAR(50)  NOT NULL COMMENT 'last 4 only when md_id_proof.mask_flag = Y',
  user_id_out   INT UNSIGNED NULL COMMENT 'fill-only',
  device_id_out VARCHAR(100) NULL COMMENT 'fill-only',
  shift_id_out  INT UNSIGNED NULL COMMENT 'fill-only',
  date_time_out DATETIME     NULL COMMENT 'fill-only',
  out_flag      ENUM('Y','N') NOT NULL DEFAULT 'N' COMMENT 'once Y stays Y',
  is_deleted    ENUM('Y','N') NOT NULL DEFAULT 'N',
  sync_flag     ENUM('Y','N') NOT NULL DEFAULT 'N',
  created_by    VARCHAR(100) NULL,
  created_at    DATETIME     NULL,
  updated_by    VARCHAR(100) NULL,
  updated_at    DATETIME     NULL,
  PRIMARY KEY (trans_id),
  UNIQUE KEY uq_luggage_receipt (customer_id, receipt_no, receipt_dt),
  KEY idx_luggage_customer_in (customer_id, date_time_in),
  KEY idx_luggage_customer_out (customer_id, date_time_out),
  KEY idx_luggage_customer_mob (customer_id, pasn_mob_no),
  KEY idx_luggage_customer_pnr (customer_id, pnr_no),
  KEY idx_luggage_customer_open (customer_id, out_flag),
  KEY idx_luggage_customer_updated (customer_id, updated_at),
  CONSTRAINT fk_luggage_customer FOREIGN KEY (customer_id) REFERENCES md_customer (customer_id),
  CONSTRAINT fk_luggage_user_in FOREIGN KEY (user_id_in) REFERENCES md_user (id),
  CONSTRAINT fk_luggage_user_out FOREIGN KEY (user_id_out) REFERENCES md_user (id),
  CONSTRAINT fk_luggage_shift_in FOREIGN KEY (shift_id_in) REFERENCES md_shift (shift_id),
  CONSTRAINT fk_luggage_shift_out FOREIGN KEY (shift_id_out) REFERENCES md_shift (shift_id),
  CONSTRAINT fk_luggage_id_proof FOREIGN KEY (id_proof_id) REFERENCES md_id_proof (id_proof_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- One bill per transaction. block_hours/first_block_rate/next_block_rate/gst_pct are snapshots.
CREATE TABLE IF NOT EXISTS td_receipt (
  trans_id         VARCHAR(36)  NOT NULL,
  customer_id      INT UNSIGNED NOT NULL,
  bill_no          VARCHAR(20)  NOT NULL,
  bill_dt          DATE         NOT NULL COMMENT 'local (IST)',
  user_id          INT UNSIGNED NOT NULL COMMENT 'md_user.id',
  device_id        VARCHAR(100) NOT NULL,
  shift_id         INT UNSIGNED NULL,
  luggage_qty      SMALLINT UNSIGNED NOT NULL,
  days_charged     SMALLINT UNSIGNED NOT NULL,
  block_hours      INT UNSIGNED  NOT NULL,
  first_block_rate DECIMAL(10,2) NOT NULL,
  next_block_rate  DECIMAL(10,2) NOT NULL,
  base_amt         DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  penal_amt        DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  net_amt          DECIMAL(10,2) NOT NULL DEFAULT 0.00 COMMENT 'GST-inclusive total',
  taxable_amt      DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  gst_pct          DECIMAL(5,2)  NOT NULL DEFAULT 0.00,
  cgst             DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  sgst             DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  igst             DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  gst_flag         ENUM('Y','N') NOT NULL DEFAULT 'N',
  pay_mode         ENUM('C','U') NOT NULL DEFAULT 'C',
  upi_ref          VARCHAR(50)  NULL,
  bill_printed     ENUM('Y','N') NOT NULL DEFAULT 'Y' COMMENT 'N = Out Without Bill Print',
  is_deleted       ENUM('Y','N') NOT NULL DEFAULT 'N',
  sync_flag        ENUM('Y','N') NOT NULL DEFAULT 'N',
  created_by       VARCHAR(100) NULL,
  created_at       DATETIME     NULL,
  updated_by       VARCHAR(100) NULL,
  updated_at       DATETIME     NULL,
  PRIMARY KEY (trans_id),
  UNIQUE KEY uq_receipt_bill (customer_id, bill_no, bill_dt),
  KEY idx_receipt_customer_dt (customer_id, bill_dt),
  KEY idx_receipt_customer_user_dt (customer_id, user_id, bill_dt),
  KEY idx_receipt_customer_updated (customer_id, updated_at),
  CONSTRAINT fk_receipt_luggage FOREIGN KEY (trans_id) REFERENCES td_luggage_in_out (trans_id),
  CONSTRAINT fk_receipt_customer FOREIGN KEY (customer_id) REFERENCES md_customer (customer_id),
  CONSTRAINT fk_receipt_user FOREIGN KEY (user_id) REFERENCES md_user (id),
  CONSTRAINT fk_receipt_shift FOREIGN KEY (shift_id) REFERENCES md_shift (shift_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- Cloud only. Rows the server refused to merge; owned by the admin (exceptions report).
CREATE TABLE IF NOT EXISTS td_sync_exception (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  customer_id   INT UNSIGNED NOT NULL,
  trans_id      VARCHAR(36)  NOT NULL,
  table_name    VARCHAR(50)  NOT NULL,
  payload       JSON         NOT NULL,
  reason        VARCHAR(255) NOT NULL,
  user_id       INT UNSIGNED NOT NULL COMMENT 'md_user.id of the pushing user',
  device_id     VARCHAR(100) NOT NULL,
  resolved_flag ENUM('Y','N') NOT NULL DEFAULT 'N',
  resolved_by   VARCHAR(100) NULL,
  resolved_at   DATETIME     NULL,
  created_at    DATETIME     NOT NULL DEFAULT (UTC_TIMESTAMP()),
  PRIMARY KEY (id),
  KEY idx_exception_trans (trans_id),
  KEY idx_exception_customer_resolved (customer_id, resolved_flag, created_at),
  CONSTRAINT fk_exception_customer FOREIGN KEY (customer_id) REFERENCES md_customer (customer_id),
  CONSTRAINT fk_exception_user FOREIGN KEY (user_id) REFERENCES md_user (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
